#!/usr/bin/env bash
# RFC-0016 K4c (section 8.1): seed the stdlib-body axis's corpus ledger.
#
# The axis answers "absent is a decline" for a routine of the toolchain's
# `lib/` the walker would walk by body. The routines the test suite walks are
# the ledger (`src/nelli/smt/stdlib_ledger.nim`): this script regenerates it.
#
# Each test is compiled (not run) in the dev container with
# `-d:nelliStdlibLedger=<file>`, one file per test; the parser appends the
# `<module>.<name>` key of every stdlib routine it reads a body of. Parsing
# happens at macro time, so a compile-only build sees every routine a run
# would walk.
#
# Probe tests are left out of the corpus. A test that exists to prove "a
# routine with no row declines" parses its probe too, so seeding from it would
# admit the probe and defeat the test. Such a file carries the marker
#   # stdlib-ledger: probe
# and `--lint` fails a file that looks like a probe but lacks it.
#
# Usage: scripts/stdlib-ledger.sh [-j N] [--check] <test.nim>...
#        scripts/stdlib-ledger.sh --lint            (no compile; CI-cheap)
#   -j N     parallel compiles (default 3)
#   --check  regenerate to a scratch file and fail if it differs from the
#            committed ledger (the drift guard; writes nothing under src/)
# Run it from a worktree at the sha being certified, never the live checkout.
set -uo pipefail
marker='# stdlib-ledger: probe'
ledger=src/nelli/smt/stdlib_ledger.nim

lint() {
  # A file that asserts a routine's decline through the stdlib axis is a probe.
  local bad=0 t
  for t in $(command grep -lE '^[^#]*(declinesUnadmitted\(|not hasStdlibRow)' tests/t*.nim); do
    if ! command grep -qF "$marker" "$t"; then
      echo "probe without '$marker': $t" >&2; bad=1
    fi
  done
  return $bad
}

jobs=3; check=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    -j) jobs="$2"; shift 2 ;;
    --check) check=1; shift ;;
    --lint) lint; exit $? ;;
    *) break ;;
  esac
done
[ "$#" -gt 0 ] || { echo "usage: $0 [-j N] [--check] tests/foo.nim... | --lint" >&2; exit 2; }
lint || exit 1

img="localhost/nelli-dev:${NELLI_IMAGE:-latest}"
dir="tests/.pins/stdlib-ledger.d"
rm -rf "$dir" "$dir.failed"; mkdir -p "$dir"
corpus=()
for t in "$@"; do
  if command grep -qF "$marker" "$t"; then echo "probe, skipped: $t" >&2
  else corpus+=("$t"); fi
done
one() {
  t="$1"
  : > "$dir/$(basename "$t")"
  timeout --signal=KILL 900 podman run --rm -v "$PWD:/work" \
    -v "$HOME/.cache/milpa:/.cache/milpa" -v "$HOME/.cache/milpa:$HOME/.cache/milpa" \
    -w /work "$img" \
    nim c --compileOnly:on --threads:on --hints:off \
      --nimcache:/tmp/ledger-nimcache-$$ \
      -d:nelliStdlibLedger=/work/$dir/$(basename "$t") "$t" \
    > "$dir/$(basename "$t").log" 2>&1 || { echo "FAILED $t" >&2; echo "$t" >> "$dir.failed"; }
}
export -f one
export PWD img dir
printf '%s\n' "${corpus[@]}" | xargs -P "$jobs" -I{} bash -c 'one {}'
# A test that does not compile contributes no keys, so the ledger would be
# silently short: refuse to write or compare anything (the compiler output is
# kept beside each key file as <test>.log, which the key concatenation skips).
if [ -s "$dir.failed" ]; then
  echo "stdlib ledger: $(wc -l < "$dir.failed") test(s) failed to compile (see $dir/<test>.log):" >&2
  cat "$dir.failed" >&2
  exit 1
fi
out="$ledger"; [ "$check" = 1 ] && out="tests/.pins/stdlib-ledger.regen.nim"
{
  echo "## RFC-0016 K4c (section 8.1): the corpus ledger of the stdlib-body axis, the"
  echo "## \`<module>.<name>\` of every routine of the toolchain's \`lib/\` the test suite"
  echo "## walks by its body. GENERATED by \`scripts/stdlib-ledger.sh\` from a corpus run"
  echo "## (the parser appends each key it reads to \`-d:nelliStdlibLedger\`); do not edit."
  echo "## A routine outside it, and outside \`stdlibAxis\`, declines \`feUnadmitted\`."
  echo "## Tests marked \`# stdlib-ledger: probe\` are not part of the corpus."
  echo "const ledgerKeys*: seq[string] = @["
  cat "$dir"/*.nim | sort -u | sed 's/\\/\\\\/g; s/"/\\"/g; s/.*/  "&",/'
  echo "]"
} > "$out"
echo "ledger: $(command grep -c '^  "' "$out") routines from ${#corpus[@]} files"
if [ "$check" = 1 ]; then
  diff -u "$ledger" "$out" || { echo "stdlib ledger drifts from a regeneration" >&2; exit 1; }
  echo "stdlib ledger matches a regeneration"
fi
